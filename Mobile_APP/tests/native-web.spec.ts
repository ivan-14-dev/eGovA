import { expect, test } from '@playwright/test'

test('Expo client: private workspace, confirmed action, upload, preview and logout', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Inscription', exact: true }).click()
  await page.getByLabel('Courriel', { exact: true }).fill(`expo-${Date.now()}@example.test`)
  await page.getByLabel('Mot de passe', { exact: true }).fill('Expo-testing-only-874!Password')
  await page.getByRole('button', { name: 'Créer mon compte', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Votre situation' })).toBeVisible()
  await page.getByLabel('Vous êtes', { exact: true }).selectOption('entreprise')
  await page.getByLabel('Entreprise ou projet', { exact: true }).fill('Entreprise Expo test')
  await page.getByLabel('Activité principale', { exact: true }).selectOption('installation')
  await page.getByRole('button', { name: 'Enregistrer mon profil' }).click()
  await expect(page.getByRole('button', { name: 'Démarches', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Démarches', exact: true }).click()
  await page.getByLabel('Filtrer les démarches').fill('P08')
  await page.getByRole('button', { name: /^\+ P08/ }).click()
  await page.getByRole('button', { name: 'Préparer ce dossier', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Votre progression' })).toBeVisible()
  await page.getByRole('button', { name: 'Assistant IA', exact: true }).click()
  await page.getByLabel('Dossier concerné', { exact: true }).selectOption({ index: 1 })
  await page.getByLabel('Votre commande ou question').fill('Échéance au 2027-05-01')
  await page.getByRole('button', { name: 'Envoyer à l’assistant' }).click()
  await expect(page.getByRole('heading', { name: 'Votre confirmation est nécessaire' })).toBeVisible()
  await page.getByRole('button', { name: 'Confirmer et enregistrer ces changements' }).click()
  await expect(page.getByLabel('Prochaine échéance (AAAA-MM-JJ)', { exact: true })).toHaveValue('2027-05-01')
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Choisir un document (PDF, PNG, JPEG)', exact: true }).click()
  await (await chooser).setFiles({
    name: 'expo-preuve.png', mimeType: 'image/png',
    buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jWZkAAAAASUVORK5CYII=', 'base64'),
  })
  await expect(page.getByText('Document choisi : expo-preuve.png')).toBeVisible()
  await page.getByLabel('Expiration de la pièce (AAAA-MM-JJ, facultatif)').fill('2000-01-01')
  await page.getByRole('button', { name: 'Ajouter la pièce', exact: true }).click()
  await page.getByRole('button', { name: 'Visualiser expo-preuve.png', exact: true }).click()
  await expect(page.getByRole('img', { name: 'expo-preuve.png' })).toBeVisible()
  await page.getByRole('button', { name: 'Fermer le document', exact: true }).click()
  await page.getByLabel('Poste de dépense', { exact: true }).fill('Coût de test')
  await page.getByLabel('Montant FCFA (vide si inconnu)', { exact: true }).fill('12000')
  await page.getByLabel('Source, devis, période et zone').fill('Devis fictif navigateur')
  await page.getByRole('button', { name: 'Ajouter au budget' }).click()
  await expect(page.getByText(/Sous-total initial · inconnu/)).toBeVisible()
  await page.getByRole('button', { name: /^Alertes \(/ }).click()
  await expect(page.getByRole('heading', { name: 'expo-preuve.png : expiré' })).toBeVisible()
  await page.getByRole('button', { name: 'Audit', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Mes points à vérifier' })).toBeVisible()
  await page.getByRole('button', { name: 'Profil', exact: true }).click()
  await page.getByRole('button', { name: 'Se déconnecter', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Connexion', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('Expo public library uses real sources and persistent favorites', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Bibliothèque', exact: true }).click()
  await expect(page.getByRole('button', { name: /80 sources · 3011 pages/ })).toBeVisible()
  await page.getByLabel('Mots-clés documentaires').fill('certification')
  await page.getByRole('button', { name: 'Chercher dans le texte des documents' }).click()
  await page.getByRole('button', { name: /^Lire la page/ }).first().click()
  await expect(page.getByText(/confiance OCR/)).toBeVisible()
  await page.getByRole('button', { name: 'Retour à la bibliothèque' }).click()
  await page.getByRole('button', { name: 'Afficher le catalogue' }).click()
  await page.getByRole('button', { name: 'Ajouter aux favoris' }).first().click()
  await page.reload()
  await page.getByRole('button', { name: 'Bibliothèque', exact: true }).click()
  await page.getByRole('switch', { name: 'Mes favoris uniquement' }).check()
  await expect(page.getByRole('button', { name: 'Retirer des favoris' })).toHaveCount(1)
})
